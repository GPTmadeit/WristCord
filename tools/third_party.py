#!/usr/bin/env python3
"""Writes native/dave/licenses/THIRD_PARTY_LICENSES.md: every Rust crate linked into
libwristcord_dave.so, with the licence texts those crates ship, deduplicated.

    python3 tools/third_party.py

Reads `cargo metadata` for the Android target and follows normal (runtime) dependencies from the
crate root. Proc-macro crates run at build time and are not linked, so they and their own
dependencies are skipped. Needs the crates in Cargo's registry cache (any build fetches them).
"""
import glob
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.join(ROOT, "native", "dave")
OUT = os.path.join(CRATE, "licenses", "THIRD_PARTY_LICENSES.md")
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|copyright)([-_.].*)?$", re.I)

MIT_TEXT = """Permission is hereby granted, free of charge, to any person obtaining a copy of this software
and associated documentation files (the "Software"), to deal in the Software without restriction,
including without limitation the rights to use, copy, modify, merge, publish, distribute,
sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or
substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT
NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND
NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES
OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN
CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE."""


def standard_text(collected, marker):
    """One canonical copy of a licence: from the crates in the tree, else from Cargo's cache."""
    for t in collected.values():
        if marker in t["body"]:
            return t["body"]
    cache = os.path.join(os.environ.get("CARGO_HOME", os.path.expanduser("~/.cargo")), "registry", "src")
    for path in sorted(glob.glob(os.path.join(cache, "*", "*", "LICENSE*"))):
        with open(path, encoding="utf-8", errors="replace") as fh:
            body = fh.read().strip()
        if body.startswith(marker) or marker in body[:200]:
            return body
    return None


def main():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", "aarch64-linux-android"],
        cwd=CRATE,
    ))
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]

    def is_proc_macro(pid):
        return any("proc-macro" in t["kind"] for t in packages[pid]["targets"])

    linked, stack = set(), [root]
    while stack:
        pid = stack.pop()
        if pid in linked:
            continue
        linked.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and not is_proc_macro(dep["pkg"]):
                stack.append(dep["pkg"])
    linked.discard(root)

    rows, texts, bare = [], {}, []
    for pid in sorted(linked, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        p = packages[pid]
        crate_dir = os.path.dirname(p["manifest_path"])
        files = sorted(f for f in os.listdir(crate_dir)
                       if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(crate_dir, f)))
        label = f'{p["name"]} {p["version"]}'
        for f in files:
            with open(os.path.join(crate_dir, f), encoding="utf-8", errors="replace") as fh:
                body = fh.read().strip()
            key = hashlib.sha256(body.encode()).hexdigest()
            texts.setdefault(key, {"body": body, "crates": []})["crates"].append(f"{label} ({f})")
        source = p.get("repository") or f'https://crates.io/crates/{p["name"]}'
        if not files:
            bare.append(p)
        rows.append((p["name"], p["version"], p.get("license") or "see source", source,
                     "" if files else " (no licence file in the crate; see its source)"))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("# Third-party licences: native/dave\n\n")
        out.write("WristCord's native library (`libwristcord_dave.so`, Discord's DAVE end-to-end "
                  "encryption) is built from the Rust crates below, at these exact versions "
                  "(`native/dave/Cargo.lock`). Generated by `tools/third_party.py`; do not edit.\n\n")
        out.write("Crates under MPL-2.0 are used unmodified; their source is available from "
                  "crates.io at the versions listed.\n\n")
        out.write("| Crate | Version | Licence | Source |\n|---|---|---|---|\n")
        for name, version, lic, source, note in rows:
            out.write(f"| {name} | {version} | {lic} | {source}{note} |\n")

        standards = {
            "Apache-2.0": standard_text(texts, "Apache License\n                           Version 2.0"),
            "MPL-2.0": standard_text(texts, "Mozilla Public License Version 2.0"),
        }
        needed = set()
        out.write("\n## Crates that publish no licence file\n\n")
        out.write("Their licence is the one declared in their Cargo manifest; the copyright holders "
                  "are the crate's listed authors.\n")
        for p in bare:
            ids = set(re.findall(r"[A-Za-z0-9.+-]+", (p.get("license") or "").replace("/", " OR ")))
            ids -= {"OR", "AND", "WITH"}
            holders = ", ".join(a.split(" <")[0] for a in p.get("authors") or []) or "the authors"
            out.write(f'\n### {p["name"]} {p["version"]} ({p.get("license")})\n\n')
            if "MIT" in ids:
                out.write(f"```text\nMIT License\n\nCopyright (c) {holders}\n\n{MIT_TEXT}\n```\n")
            else:
                for i in sorted(ids):
                    needed.add(i)
                    out.write(f"Copyright (c) {holders}. Licensed under {i}; the full text is under "
                              f"*Standard licence texts* below.\n")
        if needed:
            out.write("\n## Standard licence texts\n")
            for i in sorted(needed):
                body = standards.get(i)
                out.write(f"\n### {i}\n\n")
                out.write("```text\n" + body.replace("```", "'''") + "\n```\n" if body
                          else f"See https://spdx.org/licenses/{i}.html\n")
        out.write("\n## Licence texts shipped by the crates\n")
        for t in sorted(texts.values(), key=lambda t: t["crates"][0]):
            out.write("\n---\n\nUsed by: " + ", ".join(t["crates"]) + "\n\n")
            out.write("```text\n" + t["body"].replace("```", "'''") + "\n```\n")
    print(f"{len(rows)} crates, {len(texts)} distinct licence texts -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
